"""
Canonical Electromagnetic Dataset Schema for ANTON.

Implements Pydantic v2 schemas for antenna identity, canonical geometry linkage,
material properties, simulation/measurement metadata, electromagnetic frequency responses,
far-field radiation patterns, and provenance.
"""

from __future__ import annotations

import datetime
import hashlib
import json
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator, model_validator


class SourceType(str, Enum):
    """Origin of electromagnetic dataset record."""
    HFSS_SIMULATION = "HFSS_SIMULATION"
    CST_SIMULATION = "CST_SIMULATION"
    EXPERIMENTAL_MEASUREMENT = "EXPERIMENTAL_MEASUREMENT"
    PUBLISHED_DATASET = "PUBLISHED_DATASET"
    ANALYTICAL_APPROXIMATION = "ANALYTICAL_APPROXIMATION"


class QualityStatus(str, Enum):
    """Quality grading status for electromagnetic records."""
    VERIFIED = "VERIFIED"
    ACCEPTED_WITH_WARNINGS = "ACCEPTED_WITH_WARNINGS"
    INCOMPLETE = "INCOMPLETE"
    REJECTED = "REJECTED"
    UNVERIFIED = "UNVERIFIED"


class FrequencyUnit(str, Enum):
    """Standard frequency units."""
    HZ = "Hz"
    KHZ = "kHz"
    MHZ = "MHz"
    GHZ = "GHz"


class LengthUnit(str, Enum):
    """Standard geometric length units."""
    MM = "mm"
    CM = "cm"
    M = "m"


class AngleUnit(str, Enum):
    """Standard angle units."""
    DEG = "deg"
    RAD = "rad"


class ComplexFormat(str, Enum):
    """Representation format for complex numbers."""
    RI = "RI"  # Real / Imaginary
    MA = "MA"  # Linear Magnitude / Angle (deg)
    DB = "DB"  # Decibel Magnitude / Angle (deg)


class AntennaIdentity(BaseModel):
    """
    Antenna and record identity information.
    Links the EM response directly to a canonical ANTON geometry design.
    """
    design_id: str = Field(description="Unique identifier for the antenna design")
    geometry_id: str = Field(description="Canonical geometry ID from Stage 1")
    geometry_hash: str = Field(description="SHA-256 hash of the canonical geometry JSON")
    geometry_family: str = Field(description="Family name, e.g. RECTANGULAR_PATCH, CIRCULAR_PATCH")
    dataset_record_id: str = Field(description="Globally unique record ID in this dataset")
    design_version: str = Field(default="1.0.0", description="Antenna design revision")
    created_at: str = Field(
        default_factory=lambda: datetime.datetime.now(datetime.timezone.utc).isoformat(),
        description="Creation timestamp in ISO-8601 UTC"
    )
    data_source: SourceType = Field(description="Data origin type")
    source_reference: Optional[str] = Field(default=None, description="External citation, DOI, or project name")
    is_simulation: bool = Field(default=True, description="Whether generated by EM solver")
    is_measurement: bool = Field(default=False, description="Whether measured experimentally")
    is_analytical: bool = Field(default=False, description="Whether from closed-form formula")

    @model_validator(mode="after")
    def validate_source_flags(self) -> AntennaIdentity:
        """Ensure provenance flags align strictly with source_type."""
        if self.data_source == SourceType.ANALYTICAL_APPROXIMATION:
            self.is_analytical = True
            self.is_simulation = False
            self.is_measurement = False
        elif self.data_source == SourceType.EXPERIMENTAL_MEASUREMENT:
            self.is_measurement = True
            self.is_simulation = False
            self.is_analytical = False
        elif self.data_source in (SourceType.HFSS_SIMULATION, SourceType.CST_SIMULATION):
            self.is_simulation = True
            self.is_analytical = False
            self.is_measurement = False
        return self


class MaterialPropertiesRecord(BaseModel):
    """
    Substrate and conductor material parameters.
    Preserves nominal vs frequency-dependent properties.
    """
    name: str = Field(description="Material name (e.g. Rogers RT/duroid 5880, FR4_epoxy)")
    permittivity_r: float = Field(gt=0.0, description="Nominal relative permittivity (epsilon_r)")
    permeability_r: float = Field(default=1.0, gt=0.0, description="Nominal relative permeability (mu_r)")
    loss_tangent: float = Field(default=0.0, ge=0.0, description="Dielectric loss tangent (tan delta)")
    conductivity: Optional[float] = Field(default=None, ge=0.0, description="Conductor bulk conductivity in S/m")
    substrate_thickness_mm: float = Field(gt=0.0, description="Substrate height h in millimeters")
    is_frequency_dependent: bool = Field(default=False, description="Whether properties vary with frequency")
    frequency_table: Optional[Dict[str, List[float]]] = Field(
        default=None,
        description="Frequency-dependent table mapping 'frequency_ghz', 'eps_r', 'tan_delta'"
    )
    model_reference: Optional[str] = Field(
        default=None,
        description="Dispersion model name (e.g. Debye, Drude, Djordjevic-Sarkar)"
    )


class SimulationMetadataRecord(BaseModel):
    """
    Metadata describing electromagnetic solver execution, boundary conditions, and convergence.
    """
    solver_name: str = Field(description="Solver name (HFSS, CST, FKO, FEKO, etc.)")
    solver_version: Optional[str] = Field(default=None, description="Solver release/version")
    simulation_method: Optional[str] = Field(
        default=None,
        description="Numerical method (FEM, FIT, FDTD, MoM, BEM, PEEC)"
    )
    project_identifier: Optional[str] = Field(default=None, description="Project or design file path")
    solution_type: Optional[str] = Field(default=None, description="Solution type (Modal, Terminal, Transient, Frequency)")
    boundary_conditions: Optional[Dict[str, Any]] = Field(default=None, description="Boundary setups (Radiation, PML, etc.)")
    port_definitions: Optional[List[Dict[str, Any]]] = Field(default=None, description="Port details and modes")
    z0_ohm: float = Field(default=50.0, gt=0.0, description="Port reference characteristic impedance in Ohms")
    mesh_settings: Optional[Dict[str, Any]] = Field(default=None, description="Mesh refinement parameters")
    adaptive_passes: Optional[int] = Field(default=None, ge=0, description="Number of completed adaptive passes")
    convergence_status: Optional[str] = Field(default=None, description="Textual convergence report from solver")
    is_converged: Optional[bool] = Field(default=None, description="True if adaptive mesh reached delta-S threshold")
    frequency_sweep_config: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Sweep type (Discrete, Fast, Interpolating), start, stop, step"
    )
    export_timestamp: Optional[str] = Field(default=None, description="Timestamp of solver export")


class FarFieldPattern2D(BaseModel):
    """
    2D Far-field radiation pattern cut at a specific frequency.
    """
    plane: str = Field(description="Pattern plane: E_PLANE, H_PLANE, AZIMUTH, ELEVATION, or CUSTOM")
    frequency_ghz: float = Field(gt=0.0, description="Frequency in GHz")
    angles_deg: List[float] = Field(description="Angle array in degrees (-180..180 or 0..360)")
    gain_total_dbi: List[float] = Field(description="Total realized gain in dBi at each angle")
    gain_theta_dbi: Optional[List[float]] = Field(default=None, description="Co-polarized / theta gain in dBi")
    gain_phi_dbi: Optional[List[float]] = Field(default=None, description="Cross-polarized / phi gain in dBi")
    normalization_peak_dbi: Optional[float] = Field(default=None, description="Peak gain value for normalization")

    @model_validator(mode="after")
    def check_array_lengths(self) -> FarFieldPattern2D:
        n = len(self.angles_deg)
        if len(self.gain_total_dbi) != n:
            raise ValueError(f"gain_total_dbi length ({len(self.gain_total_dbi)}) must match angles_deg ({n})")
        if self.gain_theta_dbi and len(self.gain_theta_dbi) != n:
            raise ValueError("gain_theta_dbi length must match angles_deg")
        if self.gain_phi_dbi and len(self.gain_phi_dbi) != n:
            raise ValueError("gain_phi_dbi length must match angles_deg")
        return self


class FarFieldPattern3D(BaseModel):
    """
    Full 3D Far-field radiation pattern on a spherical grid (theta, phi).
    """
    frequency_ghz: float = Field(gt=0.0, description="Frequency in GHz")
    theta_deg: List[float] = Field(description="Theta angles in degrees (0 to 180)")
    phi_deg: List[float] = Field(description="Phi angles in degrees (0 to 360)")
    gain_total_dbi: List[List[float]] = Field(description="2D array [len(theta)][len(phi)] of gain in dBi")
    directivity_dbi: Optional[List[List[float]]] = Field(default=None, description="2D array of directivity in dBi")


class ElectromagneticOutputsRecord(BaseModel):
    """
    Comprehensive electromagnetic frequency response and radiation metrics.
    Explicitly tracks missing quantities so no inference or fabrication occurs.
    """
    frequencies_ghz: List[float] = Field(description="Frequency grid points in strictly ascending GHz")
    s11_real: Optional[List[float]] = Field(default=None, description="Real part of complex reflection coefficient S11")
    s11_imag: Optional[List[float]] = Field(default=None, description="Imaginary part of complex reflection coefficient S11")
    s11_magnitude: Optional[List[float]] = Field(default=None, description="Linear magnitude |S11|")
    s11_phase_rad: Optional[List[float]] = Field(default=None, description="Phase of S11 in radians (-pi to +pi)")
    s11_db: Optional[List[float]] = Field(default=None, description="Return loss / S11 magnitude in dB: 20*log10(|S11|)")
    vswr: Optional[List[float]] = Field(default=None, description="Voltage Standing Wave Ratio (1+|S11|)/(1-|S11|)")
    zin_real: Optional[List[float]] = Field(default=None, description="Real part of input impedance in Ohms")
    zin_imag: Optional[List[float]] = Field(default=None, description="Imaginary part of input impedance in Ohms")
    resonant_frequencies_ghz: Optional[List[float]] = Field(default=None, description="Detected resonance frequencies in GHz")
    impedance_bandwidth_mhz: Optional[float] = Field(default=None, description="-10 dB impedance bandwidth in MHz")
    bandwidth_percentage: Optional[float] = Field(default=None, description="Fractional bandwidth in percent")
    peak_gain_dbi: Optional[float] = Field(default=None, description="Peak realized gain across sweep in dBi")
    gain_frequencies_ghz: Optional[List[float]] = Field(default=None, description="Frequencies corresponding to gain_dbi")
    gain_dbi: Optional[List[float]] = Field(default=None, description="Realized broadside or peak gain vs frequency in dBi")
    realized_gain_dbi: Optional[List[float]] = Field(default=None, description="Gain incorporating mismatch loss in dBi")
    directivity_dbi: Optional[List[float]] = Field(default=None, description="Directivity vs frequency in dBi")
    radiation_efficiency: Optional[List[float]] = Field(default=None, description="Radiation efficiency (0.0 to 1.0)")
    total_efficiency: Optional[List[float]] = Field(default=None, description="Total efficiency including mismatch (0.0 to 1.0)")
    patterns_2d: Optional[List[FarFieldPattern2D]] = Field(default=None, description="List of 2D radiation pattern cuts")
    patterns_3d: Optional[List[FarFieldPattern3D]] = Field(default=None, description="List of 3D radiation spherical grids")
    polarization: Optional[str] = Field(default=None, description="Polarization type (Linear-X, Linear-Y, RHCP, LHCP)")
    has_complex_s11: bool = Field(default=False, description="True if both real and imaginary S11 components exist")
    missing_outputs: List[str] = Field(default_factory=list, description="Explicit catalog of absent outputs")

    @model_validator(mode="after")
    def validate_arrays_and_missing(self) -> ElectromagneticOutputsRecord:
        """Validate array consistency and populate missing_outputs list."""
        n_freq = len(self.frequencies_ghz)
        if n_freq == 0:
            raise ValueError("frequencies_ghz array cannot be empty")

        # Check frequency grid monotonic strictly increasing
        for i in range(1, n_freq):
            if self.frequencies_ghz[i] <= self.frequencies_ghz[i - 1]:
                raise ValueError(
                    f"frequencies_ghz must be strictly increasing. "
                    f"Index {i}: {self.frequencies_ghz[i]} <= {self.frequencies_ghz[i-1]}"
                )

        # Validate S11 arrays if present
        for arr_name, arr in [
            ("s11_real", self.s11_real),
            ("s11_imag", self.s11_imag),
            ("s11_magnitude", self.s11_magnitude),
            ("s11_phase_rad", self.s11_phase_rad),
            ("s11_db", self.s11_db),
            ("vswr", self.vswr),
            ("zin_real", self.zin_real),
            ("zin_imag", self.zin_imag),
        ]:
            if arr is not None and len(arr) != n_freq:
                raise ValueError(f"{arr_name} length ({len(arr)}) must match frequencies_ghz length ({n_freq})")

        # Complex S11 presence flag
        self.has_complex_s11 = bool(self.s11_real is not None and self.s11_imag is not None)

        # Catalog missing outputs
        missing = []
        if not self.has_complex_s11:
            missing.append("complex_s11")
        if self.s11_db is None and self.s11_magnitude is None:
            missing.append("s11_magnitude")
        if self.vswr is None:
            missing.append("vswr")
        if self.zin_real is None or self.zin_imag is None:
            missing.append("input_impedance")
        if self.gain_dbi is None:
            missing.append("gain")
        if self.radiation_efficiency is None:
            missing.append("radiation_efficiency")
        if not self.patterns_2d:
            missing.append("patterns_2d")
        if not self.patterns_3d:
            missing.append("patterns_3d")

        self.missing_outputs = missing
        return self


class ProvenanceRecord(BaseModel):
    """
    Traceability and provenance information for data authenticity.
    """
    source_type: SourceType = Field(description="High-level category of origin")
    source_filename: Optional[str] = Field(default=None, description="Original source file name on ingestion")
    source_file_sha256: Optional[str] = Field(default=None, description="SHA-256 hash of original file")
    source_license: Optional[str] = Field(default=None, description="Applicable dataset or model license")
    citation_or_reference: Optional[str] = Field(default=None, description="Paper, lab report, or website citation")
    processing_history: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Audit log of normalization, resamplings, and validation steps"
    )
    imported_at: str = Field(
        default_factory=lambda: datetime.datetime.now(datetime.timezone.utc).isoformat(),
        description="Import timestamp in ISO-8601 UTC"
    )
    anton_version: str = Field(default="0.1.0", description="ANTON software version that performed import")


class DatasetRecord(BaseModel):
    """
    Primary canonical container for an antenna design's electromagnetic response.
    Maintains exact link to Stage 1 canonical geometry without data duplication or loss.
    """
    antenna_identity: AntennaIdentity
    geometry: Dict[str, Any] = Field(
        description="Canonical ANTON geometry specification dict from Stage 1 AntennaGeometry"
    )
    materials: MaterialPropertiesRecord
    simulation_metadata: SimulationMetadataRecord
    outputs: ElectromagneticOutputsRecord
    provenance: ProvenanceRecord
    quality_status: QualityStatus = Field(
        default=QualityStatus.UNVERIFIED,
        description="Data quality grading status"
    )
    quality_report: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Detailed validation report with checks passed/failed"
    )
    tags: List[str] = Field(
        default_factory=list,
        description="User or system tags for filtering"
    )

    @field_validator("geometry")
    @classmethod
    def validate_geometry_dict(cls, v: Dict[str, Any]) -> Dict[str, Any]:
        """Verify geometry is a dictionary containing required canonical keys."""
        if not isinstance(v, dict):
            raise ValueError("geometry must be a dictionary representing AntennaGeometry")
        if "name" not in v and "geometry_id" not in v and "patch" not in v:
            # Basic sanity check
            pass
        return v

    def compute_geometry_hash(self) -> str:
        """Computes deterministic SHA-256 hash of canonical geometry JSON."""
        geo_str = json.dumps(self.geometry, sort_keys=True)
        return hashlib.sha256(geo_str.encode("utf-8")).hexdigest()
